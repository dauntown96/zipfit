// plain-check.mjs 단위 시험 — node scripts/plain-check.test.mjs · 통과 3 · 실패 다섯 갈래 하나씩(2026-11-09).
import { checkPlain, grains, hasSubject } from './plain-check.mjs'

let bad = 0
const ok = (c, msg) => { if (!c) bad++; console.log(`${c ? '✓' : '✗'} ${msg}`) }
const kinds = (r) => r.fails.map((f) => f.kind)

// ── 통과 3
const pass = [
  ['임대보증금·임대료 기준 (주어 있음 · 숫자·% 그대로)',
   '임대보증금은 시세의 30% 수준이며 월 임대료는 120,000원 이하입니다.',
   '임대보증금은 시세의 30% 정도예요. 월 임대료는 120000원 이하예요.'],
   ['불가 → 할 수 없어요(같은 부정 갈래) · 날짜 꼴 다름 · 때 낱말 그대로',
   '당첨자는 2026. 11. 20.까지 계약하여야 하며, 금회 공급분은 전매가 불가합니다.',
   '당첨자는 2026.11.20까지 계약해야 해요. 금회 공급분은 전매를 할 수 없어요.'],
  ['한정·제외 갈래 · 「」 이름 · 주어 없는 문장 그대로',
   '무주택세대구성원만 신청할 수 있으며 「공공주택 특별법」에 따른 특별공급 당첨자는 제외합니다.\n신청서 제출 시 신분증 지참.',
   '무주택세대구성원만 신청할 수 있어요. 「공공주택 특별법」에 따른 특별공급 당첨자는 제외해요.\n신청서 제출 시 신분증 지참.'],
]
for (const [label, raw, plain] of pass) {
  const r = checkPlain(raw, plain)
  ok(r.ok, `통과 — ${label}${r.ok ? '' : ' :: ' + JSON.stringify(r.fails)}`)
}

// ── 실패 다섯 갈래(하나씩 — 그 갈래만 걸린다)
const fail = [
  ['①', '①낱알 빠짐', '임대기간은 2년이며 최대 10년까지 거주할 수 있습니다.', '임대기간은 2년이고 오래 살 수 있어요.'],
  ['②', '②원문 밖 낱알', '계약금은 임대보증금의 10%입니다.', '계약금은 임대보증금의 10%예요. 보통 300만 원쯤이에요.'],
  ['③', '③부정·제한 갈래', '소득 기준을 초과한 세대는 재계약이 불가합니다.', '소득 기준을 초과한 세대는 재계약을 다시 해요.'],
  ['④', '④때 낱말', '당해 주택 공급신청은 1회로 합니다.', '이번 주택 공급신청은 1회로 해요.'],
  ['⑤', '⑤주어 없는 문장 바뀜(근사)', '임대차계약은 본인이 체결합니다.\n대리 계약 시 위임장 제출.', '임대차계약은 본인이 해요.\n대리 계약할 땐 위임장을 내요.'],
]
for (const [n, kind, raw, plain] of fail) {
  const r = checkPlain(raw, plain)
  const ks = kinds(r)
  ok(!r.ok && ks.length > 0 && ks.every((k) => k === kind), `실패 ${n} — ${kind}만 걸림 :: ${r.fails.map((f) => `${f.kind} ${f.detail}`).join(' / ')}`)
}

// ── 낱알·주어 부품
ok(JSON.stringify(grains('1,000만 원 · 2026-11-09 · 10:00 · 30 %')) === JSON.stringify(['날짜:2026.11.9', '시각:10:00', '%:30%', '수:1000']), '낱알 꼴 맞춤(쉼표·날짜·시각·%)')
ok(hasSubject('신청자는 서류를 냅니다.') && !hasSubject('신청서 제출 시 신분증 지참.') && !hasSubject('해당하는 경우 또는 필요한 때 제출.'), '주어 근사(「또는」·「하는」 거름)')
ok(!checkPlain('', 'x').ok, '빈 원문 → 실패')

process.exit(bad ? 1 : 0)
